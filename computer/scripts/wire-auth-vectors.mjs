#!/usr/bin/env node
// The shared signature vectors (work 084): src/signed-header.ts →
// schema/wire-auth-vectors.json, which blue (wire Worker, ticket minting) and
// opc reproduce byte for byte. Deterministic: fixed keys and clocks.
//
//   node scripts/wire-auth-vectors.mjs           write it
//   node scripts/wire-auth-vectors.mjs --check   compare only

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { register } from 'tsx/esm/api';

register();
const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'schema/wire-auth-vectors.json');
const S = await import(path.join(ROOT, 'src/signed-header.ts'));

const NOW = 1_800_000_000_000;
const KEY = 'wvKchOLW_FTP0NokuvL3tl2OEXIXZklLRTZLhoTXXHU';
const TICKET_KEY = 'opc-wire-v1 test ticket key';
const H = S.WIRE_HEADERS;

const wireCase = (claims, now = NOW) => {
  const headers = S.signWire(KEY, claims, now);
  const exp = now + S.WIRE_SIGNATURE_TTL_MS;
  return { claims: { ...claims, exp }, now, scopeJson: Buffer.from(headers[H.scope], 'base64url').toString(), message: `wire|${claims.member}|${claims.keyId}|${claims.client}|${headers[H.scope]}|${exp}`, headers };
};
const wire = [
  wireCase({ member: 'usr_0123456789ab', keyId: 'key_0123456789ab', client: 'opc/0.1.0', scope: {} }),
  wireCase({ member: 'usr_0123456789ab', keyId: 'key_0123456789ab', client: 'opc/0.1.0', scope: { scopes: ['sessions:read', 'sessions:write', 'asks:answer', 'terminals'], until: NOW + 86_400_000 } }),
  wireCase({ member: 'usr_0123456789ab', keyId: 'key_0123456789ab', client: '', scope: { sessionIds: ['cs_0123456789abcdef', 'cs_ghjkmnpqrstvwxyz'], readOnly: true, until: NOW + 3_600_000 } }),
];
const base = wire[1].headers;
const set = (k, v) => ({ ...base, [k]: v });
const refuse = [
  { why: 'expired', headers: base, now: wire[1].claims.exp },
  { why: 'expiry too far ahead (forged clock)', headers: wire[1].headers, now: NOW - S.CLOCK_SKEW_MS - 1 },
  { why: 'wrong key', key: Buffer.alloc(32, 7).toString('base64url'), headers: base, now: NOW },
  { why: 'member changed', headers: set(H.member, 'usr_ffffffffffff'), now: NOW },
  { why: 'key id changed', headers: set(H.keyId, 'key_ffffffffffff'), now: NOW },
  { why: 'client changed', headers: set(H.client, 'opc/9.9.9'), now: NOW },
  { why: 'scope widened', headers: set(H.scope, S.encodeScope({ until: NOW + 86_400_000 })), now: NOW },
  { why: 'malformed auth', headers: set(H.auth, `v1.${base[H.auth]}`), now: NOW },
  { why: 'missing member', headers: set(H.member, undefined), now: NOW },
  { why: 'a ticket is not an edge signature', headers: set(H.auth, 'tk_e30.AAAA'), now: NOW },
];

const ticketCase = (claims, now = NOW) => {
  const ticket = S.mintTicket(TICKET_KEY, claims, now);
  return { claims: { v: 1, ...claims, exp: now + S.TICKET_TTL_MS }, now, ticket };
};
const tc = { org: 'org_0123456789ab', member: 'usr_0123456789ab', computer: 'cmp_0123456789ab', tunnelId: 't0123456789ab', keyId: 'key_0123456789ab', client: 'opc/0.1.0' };
const tickets = [
  ticketCase({ ...tc, scope: {} }),
  ticketCase({ ...tc, client: 'browser', scope: { sessionIds: ['cs_0123456789abcdef'], readOnly: true } }),
];
const t0 = tickets[1].ticket;
const [body, mac] = t0.slice(3).split('.');
const tRefuse = [
  { why: 'expired', ticket: t0, now: tickets[1].claims.exp },
  { why: 'tampered payload', ticket: `tk_${Buffer.from(JSON.stringify({ ...tickets[1].claims, scope: {} })).toString('base64url')}.${mac}`, now: NOW },
  { why: 'wrong key', ticket: S.mintTicket('another key', { ...tc, scope: {} }, NOW), now: NOW },
  { why: 'no prefix', ticket: `${body}.${mac}`, now: NOW },
  { why: 'longer than 1024', ticket: S.mintTicket(TICKET_KEY, { ...tc, client: 'x'.repeat(1000), scope: {} }, NOW), now: NOW },
];

const vectors = {
  $comment: 'Work 084 shared vectors. Generated by calvin scripts/wire-auth-vectors.mjs from src/signed-header.ts (format: blue, requests-calvin.md). blue and opc must reproduce every output byte for byte. Times are ms since the epoch; header names are lowercase.',
  preview: { key: KEY, now: NOW, port: 5173, message: `5173|${NOW + 60_000}`, header: S.signPreview(KEY, 5173, NOW), rule: 'X-Preview-Auth: <expiry>.<b64u HMAC-SHA256(b64u-decode(key), "<port>|<expiry>")>, expiry = now + 60000' },
  wire: {
    key: KEY,
    rule: 'X-Wire-Auth: <exp>.<b64u HMAC-SHA256(b64u-decode(key), "wire|<member>|<keyId>|<client>|<X-Wire-Scope>|<exp>")>; X-Wire-Scope = b64u(JSON {scopes?,sessionIds?,readOnly?,until?} in that order); exp = now + 30000; the relay accepts now < exp <= now + 30000 + 30000 (clock skew)',
    cases: wire,
    refuse: refuse.map((r) => ({ ...r, headers: Object.fromEntries(Object.entries(r.headers).filter(([, v]) => v !== undefined)) })),
  },
  ticket: {
    wireTicketKey: TICKET_KEY,
    macKey: S.ticketKey(TICKET_KEY).toString('base64url'),
    rule: 'tk_<b64u(JSON payload)>.<b64u HMAC-SHA256(K, "tk_" + b64u(payload))>; K = HKDF-SHA256(utf8(WIRE_TICKET_KEY), salt empty, info "opc-wire-v1\\0", 32); exp = now + 600000; at most 1024 characters',
    cases: tickets,
    refuse: tRefuse,
  },
};
const text = `${JSON.stringify(vectors, null, 2)}\n`;
if (process.argv.includes('--check')) {
  let committed = '';
  try { committed = readFileSync(OUT, 'utf8'); } catch {}
  if (committed !== text) {
    console.error('FAIL schema/wire-auth-vectors.json differs from src/signed-header.ts: run node scripts/wire-auth-vectors.mjs and commit it');
    process.exit(1);
  }
  console.log('wire-auth vectors ok');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
